"""Small structural interfaces. Records retain existing units and monotonic clocks."""
from typing import Any, Protocol


class EventSink(Protocol):
    def emit(self, stream: str, timestamp: float, sequence: int,
             payload: dict[str, Any], source_timestamp: float | None = None) -> None: ...
    def event(self, name: str, detail: str = "") -> None: ...
    def control(self, enabled: bool, reason: str = "") -> None: ...


class ControlObserver(Protocol):
    def tracking(self, tracking: dict, sequence: int) -> None: ...
    def arm_target(self, command: Any, accepted_pose: Any, sequence: int) -> None: ...
    def hand_target(self, result: dict, sequence: int) -> None: ...
    def control(self, enabled: bool, reason: str = "") -> None: ...
